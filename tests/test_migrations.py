"""Migrations against a real Postgres.

Skipped unless ``TEST_DATABASE_URL`` points at an empty, throwaway database: CI starts one
as a service container; locally, ``docker compose up -d db`` and see the README. Every test
starts from an empty schema and leaves it empty.
"""

import os
from collections.abc import Iterator
from datetime import UTC, datetime
from pathlib import Path

import pytest
from alembic import command
from alembic.config import Config
from alembic.util.exc import AutogenerateDiffsDetected
from sqlalchemy import Engine, create_engine, inspect, text
from sqlalchemy.exc import IntegrityError

TEST_DATABASE_URL = os.environ.get("TEST_DATABASE_URL")
ROOT = Path(__file__).resolve().parents[1]

pytestmark = [
    pytest.mark.postgres,
    pytest.mark.skipif(not TEST_DATABASE_URL, reason="TEST_DATABASE_URL is not set"),
]


@pytest.fixture
def alembic_config() -> Config:
    config = Config(str(ROOT / "alembic.ini"))
    config.set_main_option("script_location", str(ROOT / "migrations"))
    config.set_main_option("sqlalchemy.url", str(TEST_DATABASE_URL))
    config.attributes["configure_logger"] = False
    return config


@pytest.fixture
def engine(alembic_config: Config) -> Iterator[Engine]:
    engine = create_engine(str(TEST_DATABASE_URL))
    command.downgrade(alembic_config, "base")
    yield engine
    command.downgrade(alembic_config, "base")
    engine.dispose()


@pytest.fixture
def migrated(alembic_config: Config, engine: Engine) -> Engine:
    command.upgrade(alembic_config, "head")
    return engine


def user_tables(engine: Engine) -> set[str]:
    return set(inspect(engine).get_table_names()) - {"alembic_version"}


def test_upgrade_creates_every_table(migrated: Engine) -> None:
    assert len(user_tables(migrated)) == 12


def test_models_and_migrations_do_not_drift(alembic_config: Config, migrated: Engine) -> None:
    try:
        command.check(alembic_config)
    except AutogenerateDiffsDetected as exc:  # pragma: no cover - only on a real drift
        pytest.fail(f"models differ from migrations; run alembic revision --autogenerate: {exc}")


def test_downgrade_removes_everything_and_upgrade_works_again(
    alembic_config: Config, migrated: Engine
) -> None:
    command.downgrade(alembic_config, "base")
    assert user_tables(migrated) == set()

    command.upgrade(alembic_config, "head")
    assert len(user_tables(migrated)) == 12


def seed_race(engine: Engine) -> None:
    """One meeting, one race session, one driver, one lap."""
    start = datetime(2026, 10, 11, 12, 0, tzinfo=UTC)
    with engine.begin() as conn:
        conn.execute(
            text(
                "INSERT INTO meetings (meeting_key, year, meeting_name, date_start) "
                "VALUES (1296, 2026, 'Singapore Grand Prix', :start)"
            ),
            {"start": start},
        )
        conn.execute(
            text(
                "INSERT INTO sessions (session_key, meeting_key, session_type, session_name, date_start)"
                " VALUES (11388, 1296, 'Race', 'Race', :start)"
            ),
            {"start": start},
        )
        conn.execute(
            text(
                "INSERT INTO session_drivers (session_key, driver_number, name_acronym, full_name)"
                " VALUES (11388, 1, 'VER', 'Max VERSTAPPEN')"
            )
        )
        conn.execute(
            text(
                "INSERT INTO laps (session_key, driver_number, lap_number, lap_duration)"
                " VALUES (11388, 1, 1, 109.7)"
            )
        )


def count(engine: Engine, table: str) -> int:
    with engine.connect() as conn:
        return int(conn.execute(text(f"SELECT count(*) FROM {table}")).scalar_one())  # noqa: S608


def test_defaults_are_applied(migrated: Engine) -> None:
    seed_race(migrated)

    with migrated.connect() as conn:
        status = conn.execute(text("SELECT load_status FROM sessions")).scalar_one()
        pit_flags = conn.execute(text("SELECT is_pit_in_lap, is_pit_out_lap FROM laps")).one()

    assert status == "pending"
    assert tuple(pit_flags) == (False, False)


def test_upsert_on_the_primary_key_keeps_one_row(migrated: Engine) -> None:
    seed_race(migrated)

    with migrated.begin() as conn:
        conn.execute(
            text(
                "INSERT INTO laps (session_key, driver_number, lap_number, lap_duration)"
                " VALUES (11388, 1, 1, 99.1)"
                " ON CONFLICT (session_key, driver_number, lap_number)"
                " DO UPDATE SET lap_duration = EXCLUDED.lap_duration"
            )
        )

    assert count(migrated, "laps") == 1


@pytest.mark.parametrize(
    ("statement", "constraint"),
    [
        (
            "INSERT INTO laps (session_key, driver_number, lap_number) VALUES (11388, 99, 2)",
            "fk_laps_session_key_driver_number_session_drivers",
        ),
        (
            "INSERT INTO laps (session_key, driver_number, lap_number, lap_duration)"
            " VALUES (11388, 1, 2, -1)",
            "ck_laps_lap_duration_positive",
        ),
        ("UPDATE sessions SET load_status = 'done'", "ck_sessions_load_status"),
        (
            "INSERT INTO safety_car_periods (session_key, kind, start_lap) VALUES (11388, 'RED', 3)",
            "ck_safety_car_periods_kind",
        ),
    ],
)
def test_constraints_reject_bad_rows(migrated: Engine, statement: str, constraint: str) -> None:
    seed_race(migrated)

    with pytest.raises(IntegrityError, match=constraint), migrated.begin() as conn:
        conn.execute(text(statement))


def test_deleting_a_meeting_deletes_its_data_but_not_run_history(migrated: Engine) -> None:
    seed_race(migrated)
    with migrated.begin() as conn:
        conn.execute(text("INSERT INTO ingestion_runs (session_key, status) VALUES (11388, 'ok')"))
        conn.execute(text("DELETE FROM meetings WHERE meeting_key = 1296"))

    assert [count(migrated, t) for t in ("sessions", "session_drivers", "laps")] == [0, 0, 0]
    assert count(migrated, "ingestion_runs") == 1
